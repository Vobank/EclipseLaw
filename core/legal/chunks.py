"""
Нарезка длинных статей на фрагменты для поиска.

Зачем. Статья 3.4 Процессуального кодекса — 5251 символ: там и порядок
задержания госслужащего, и семь примечаний про вызов прокурора,
начальства, сроки и рацию департамента. Один вектор на такую статью
размазан по десятку тем сразу, и на вопрос «как часто вызывать
прокурора в рацию» она не находилась вовсе — хотя ответ лежит в её
Примечании 5 дословно. Полнотекстовый поиск тоже её терял: BM25 делит
на длину документа, и редкое слово в длинной статье весит мало.

Поэтому длинные статьи режутся на куски, каждый со своим вектором и
своей строкой в полнотекстовом индексе. Найденный кусок ссылается на
свою статью — ответ по-прежнему про статью целиком, но в контекст
модели идёт та её часть, о которой спросили.

Режем по смысловым границам самого текста — «Примечание 2:», «в)»,
«Этап 3.» — а не по счётчику символов: в правовом тексте разрыв
посреди условия меняет смысл нормы на противоположный.
"""
from __future__ import annotations

import re

# Граница, с которой начинается новая мысль внутри статьи. Порядок
# важен: примечание сильнее подпункта, потому что внутри примечания
# подпункты тоже встречаются.
_BOUNDARY = re.compile(
    r"(?=(?:"
    r"Примечание\s*\d*\s*:|"
    r"Исключение\s*\d*\s*:|"
    r"Этап\s+\d+|"
    # Подпункт «а)», «б)» — но только как начало пункта, а не как
    # ссылка внутри предложения («в соответствии с пунктом б)»).
    r"(?<![а-яёa-z])[а-яё]\)\s|"
    r"\d{1,2}[.)]\s+(?=[А-ЯЁ])"
    r"))", re.IGNORECASE)

# Целевой размер куска. Меньше — теряется условие, при котором норма
# работает; больше — кусок снова становится «обо всём сразу».
TARGET = 700
MIN_CHUNK = 200

# Ниже этого порога статью не трогаем: короткая норма и так находится
# целиком, а лишние строки в индексе только размывают выдачу.
SPLIT_ABOVE = 900


def _sentences(text: str) -> list[str]:
    """Запасное деление — по предложениям, когда границ пунктов нет."""
    parts = re.split(r"(?<=[.;!?])\s+(?=[А-ЯЁA-Z])", text)
    return [p for p in parts if p.strip()]


# Начало самостоятельной мысли: примечание живёт отдельно от пункта,
# к которому относится, и склеивать его с соседом не стоит — искать
# будут именно его («оповещение повторять каждые 15 минут»).
_STANDALONE = re.compile(r"^(?:Примечание|Исключение)", re.IGNORECASE)


def _pack(pieces: list[str]) -> list[str]:
    """Склеивает мелкие куски до целевого размера, не рвя крупные."""
    result: list[str] = []
    current = ""
    for piece in pieces:
        piece = piece.strip()
        if not piece:
            continue
        if not current:
            current = piece
        elif _STANDALONE.match(piece):
            # Примечание всегда начинает свой кусок. Иначе «оповещение
            # повторять каждые 15 минут» тонет в хвосте предыдущего
            # перечисления и находится только вместе с ним — а
            # спрашивают именно его.
            result.append(current)
            current = piece
        elif len(current) + len(piece) + 1 <= TARGET:
            current = f"{current} {piece}"
        else:
            result.append(current)
            current = piece
    if current:
        # Хвост короче минимума прилепляем к предыдущему куску, иначе
        # в индекс попадает обрывок вроде «Примечание 7:» без текста.
        if result and len(current) < MIN_CHUNK:
            result[-1] = f"{result[-1]} {current}"
        else:
            result.append(current)
    return result


def _by_words(text: str) -> list[str]:
    """Аварийная нарезка по словам — когда границ в тексте нет вовсе."""
    words = text.split()
    result, current = [], ""
    for word in words:
        if current and len(current) + len(word) + 1 > TARGET:
            result.append(current)
            current = word
        else:
            current = f"{current} {word}".strip()
    if current:
        result.append(current)
    return result


def split_rule(text: str, *, split_above: int = SPLIT_ABOVE) -> list[str]:
    """Фрагменты статьи. Короткая статья возвращается одним куском.

    Возвращает именно куски исходного текста: ничего не пересказывает
    и не выбрасывает, иначе в ответ уйдёт не то, что написано в законе.
    """
    text = " ".join((text or "").split())
    if len(text) <= split_above:
        return [text] if text else []

    pieces = [p for p in _BOUNDARY.split(text) if p.strip()]
    # Границ не нашлось — статья написана сплошным текстом.
    if len(pieces) < 2:
        pieces = _sentences(text)

    chunks = _pack(pieces)

    # Куски, которые сами по себе длиннее целевого размера, дорезаем
    # по предложениям: одно примечание бывает и на полторы тысячи.
    result: list[str] = []
    for chunk in chunks:
        if len(chunk) <= TARGET * 2:
            result.append(chunk)
        else:
            pieces = _pack(_sentences(chunk))
            # Предложений тоже может не найтись: встречаются статьи
            # сплошным текстом без единой точки. Тогда режем по словам —
            # некрасиво, но лучше, чем один кусок на две тысячи знаков,
            # ради которого всё это и затевалось.
            if len(pieces) == 1 and len(pieces[0]) > TARGET * 2:
                pieces = _by_words(pieces[0])
            result.extend(pieces)
    return result or [text]
