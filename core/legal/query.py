# Вопрос про ответственность: «что будет за», «какая статья», «сколько
# дадут». В таких вопросах человеку нужен кодекс, а не внутренний устав
# фракции с дисциплинарными взысканиями для сотрудников.
LIABILITY = re.compile(
    # Только обороты, которые встречаются в вопросе и не встречаются в
    # тексте самого закона. Отдельные слова «штраф», «нарушение»,
    # «ответственность» сюда не годятся: они стоят внутри обычных
    # статей, и поправка срабатывала там, где вопроса нет вообще —
    # аудит базы это и показал тремя новыми промахами.
    #
    # «что будет», «что там за халатность будет», «что мне за это
    # грозит»: между «что» и «будет» человек успевает вставить тему
    # вопроса, поэтому между ними допускается несколько слов.
    r"что\s+(?:\S+\s+){0,4}?(?:будет|грозит|светит|дадут|бывает|карается)|"
    # «что предполагается за …», «что положено за …». Слово «за»
    # обязательно: без него оборот встречается и в самих нормах
    # («предполагается, что сотрудник действует добросовестно»).
    r"что\s+(?:\S+\s+){0,3}?(?:предполагается|положено|полагается)\s+за\b|"
    r"чем\s+грозит|"
    r"кака[яйое]+\s+(?:стать|наказан|ответственност|срок)|"
    r"по\s+како[йм]\s+стать|"
    # «за какую статью меня задержат» — тот же вопрос, что
    # «по какой статье», но так спрашивают чаще.
    r"за\s+каку[юя]\s+стать|за\s+что\s+(?:меня|его|нас)\s+(?:задерж|посад|аресту)|"
    r"скольк[оа]\s+(?:дад|сяд|лет|мин|получ)|"
    # «наказание за ...» сюда не годится, хотя выглядит подходяще:
    # ровно так начинается обычная норма «Ответственность за нарушение
    # данного кодекса предусмотрена...». Вопросительные формы этого
    # оборота уже покрыты выше («какое наказание за», «что будет за»).
    r"это\s+законно|мне\s+что-?то\s+будет",
    re.IGNORECASE)

# Вопрос про порядок и права: «меня задержали, что делать», «имеет ли
# право обыскать», «сколько можно держать в КПЗ». Здесь нужен не состав
# преступления, а Процессуальный кодекс: кто что обязан сделать и в
# каком порядке. Без этой поправки на «меня задержали без объяснения
# причин» сверху выходил внутренний устав LSPD с запретом сотруднику
# патрулировать в одиночку — формально про задержание, по делу мимо.
PROCEDURE = re.compile(
    r"имеет\s+ли\s+прав|"
    r"им(?:еет|еют)\s+прав|"
    r"обязан\s+ли|"
    r"(?:мои|моих)\s+прав|"
    r"могут\s+ли\s+(?:они|меня|мне)|"
    r"(?:меня|нас)\s+(?:задержал|арестовал|обыскал|остановил|закрыл)|"
    r"что\s+(?:мне\s+)?делать|"
    r"как\s+(?:мне\s+)?(?:обжаловать|оспорить|подать|защит)|"
    r"правомерн|законно\s+ли|"
    r"скольк[оа]\s+(?:можно|имеют\s+прав|часов|суток)\s*(?:держ|удерж)?",
    re.IGNORECASE)

# Вопрос-перечисление: «кто относится к неприкосновенным лицам»,
# «какие бывают ордера», «что входит в состав». Ответ на него — список
# и ссылка в конце, без объяснений: человек и так знает, о чём спросил,
# ему нужен перечень, который можно зачитать вслух.
LISTING = re.compile(
    r"(?:кто|что|кого|каки[ех]|какие)\s+(?:\S+\s+){0,2}?"
    r"(?:относится|относятся|относят|являются|является|считается|"
    r"считаются|входит|входят|бывают|существуют|признаются|"
    # «какие права имеет задержанный» — тот же перечень, только
    # спрошенный иначе. Без этих форм статья с самим перечнем
    # оставалась восьмой в выдаче и до модели не доходила.
    r"имеет|имеют|имеются|положены|предоставляются|даются)|"
    r"\bперечисл|"
    r"\bсписок\s+|"
    r"кто\s+так(?:ие|ой|ая)|"
    r"куда\s+относятся",
    re.IGNORECASE)

_WORD = re.compile(r"[а-яёa-z0-9]+(?:\.[0-9]+)*", re.IGNORECASE)


def is_liability_question(question: str) -> bool:
    """Спрашивают ли про наказание — тогда кодексы важнее уставов."""
    return LIABILITY.search(question) is not None


def is_list_question(question: str) -> bool:
    """Просят ли перечень — тогда ответ это список, а не объяснение."""
    return LISTING.search(question) is not None


def is_procedure_question(question: str) -> bool:
    """Спрашивают ли про порядок и права — тогда важнее Процессуальный.

    Вопрос про срок наказания сюда не относится, даже если в нём есть
    слово «задержали»: человеку нужна статья, а не порядок задержания.
    Поэтому проверка на ответственность имеет преимущество.
    """
    if LIABILITY.search(question):
        return False
    return PROCEDURE.search(question) is not None


# Связки: слово само по себе значит одно, а в паре с другим — другое.
# «Пристрелила воров» — обычное убийство, статья 6.4. «Пристрелил
# полицейского» — посягательство на жизнь сотрудника, статья 17.1.
# Словарём одиночных слов это не выразить: подставляя «посягательство
# на жизнь» на любой выстрел, бот отвечал 17.1 про бабку с ружьём,
# хотя никаких сотрудников в деле не было.
DEFAULT_COMBOS = (
    {"any": ("убил", "убива", "убийств", "застрел", "пристрел", "завал",
             "нападени", "напал"),
     "with": ("полицейск", "мент", "коп", "сотрудник", "офицер", "лспд",
              "lspd", "фиб", "fib", "госслужащ"),
     "add": "посягательство на жизнь сотрудника государственной организации"},
)


def _combo_additions(question: str, combos) -> list[str]:
    """Что дописать из-за сочетания слов, а не отдельных слов."""
    lowered = question.lower()
    found: list[str] = []
    for combo in combos or ():
        if not any(word in lowered for word in combo.get("any", ())):
            continue
        if not any(word in lowered for word in combo.get("with", ())):
            continue
        text = combo.get("add", "")
        if text and text not in found:
            found.append(text)
    return found


def normalize(question: str, slang: dict | None = None,
              stopwords=None, combos=None) -> str:
    """Чистит вопрос от обвязки и дописывает юридические синонимы.

    Возвращает исходный вопрос, если после чистки почти ничего не
    осталось: короткий запрос вроде «арест» состоит из одного слова, и
    ошибочно вычеркнутое слово оставило бы поиск вообще без темы.
    """
    slang = DEFAULT_SLANG if slang is None else slang
    stop = DEFAULT_STOPWORDS if stopwords is None else frozenset(stopwords)

    words = [m.group() for m in _WORD.finditer(question)]

    additions: list[str] = _combo_additions(
        question, DEFAULT_COMBOS if combos is None else combos)
    for word in (w.lower() for w in words):
        for prefix, legal in slang.items():
            if word.startswith(prefix):
                if legal not in additions:
                    additions.append(legal)
                break

    # Вырезаем стоп-слова прямо из строки, а не пересобираем её из
    # токенов. Пересборка попутно съедала регистр и знаки препинания —
    # и это не мелочь: на аудите базы закон о военном положении
    # переставал находиться по собственному тексту, хотя ни одного
    # стоп-слова в нём не было и убирать было нечего.
    cleaned = _WORD.sub(
        lambda m: "" if m.group().lower() in stop else m.group(), question)
    cleaned = re.sub(r"\s+", " ", cleaned).strip()

    if len(_WORD.findall(cleaned)) < 1:
        # Вопрос состоял из одних стоп-слов — чистить нечего.
        cleaned = question

    return " ".join([cleaned] + additions) if additions else cleaned
