def document_prompt(samples: str, skeleton: str, dictation: str,
                    form: str = "", court: bool = False,
                    law: str = "", charges: str = "",
                    episodes: str = "") -> str:
    """Промпт генератора документов (ТЗ 5.5).

    `form` — бумага, которую человек выбрал сам: «ОПРЕДЕЛЕНИЕ о
    принятии искового заявления». Угадывать её по надиктовке нельзя:
    факты дела одни и те же, а бумаг из них пишется несколько разных.
    """
    prompt = DOCUMENT
    if court:
        prompt += COURT_JURISDICTION
    if form:
        prompt += (f"\n\nОФОРМЛЯЕМ ИМЕННО ЭТУ БУМАГУ: {form}.\n"
                   "Вид документа выбран человеком — не подменяй его "
                   "другим, даже если надиктовка похожа на иной случай. "
                   "Заголовок бумаги должен соответствовать выбранному.")
    prompt += DOCUMENT_TASK.format(
        samples=samples or "(образцов пока нет — опирайся на структуру ниже)",
        skeleton=skeleton or "(структура не задана)",
        dictation=dictation)
    # Выдержки идут ПОСЛЕ образцов, а не до. Сначала они стояли в
    # начале промпта: между ними и заданием вклинивались четыре тысячи
    # знаков образцов, и модель ориентировалась на образцы, а номера
    # статей брала по памяти. В прокурорское дело так попала статья
    # 6.1 о телесных повреждениях за незачитанные права.
    if law:
        prompt += DOCUMENT_LAW.format(law=law)
    # Самым последним — список статей обвинения: он короткий и должен
    # остаться перед глазами модели, когда она дойдёт до раздела
    # с обвинением.
    if charges:
        prompt += DOCUMENT_CHARGES.format(charges=charges)
    # Эпизоды идут последними: это перечень того, что обязано попасть
    # в документ, и он должен остаться перед глазами модели.
    if episodes:
        prompt += DOCUMENT_EPISODES.format(episodes=episodes)
    return prompt


