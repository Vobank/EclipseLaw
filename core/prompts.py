# Нужно короткое «о чём она».
ARTICLE_FORMAT = """

СПРОСИЛИ ПРО КОНКРЕТНУЮ СТАТЬЮ. Номер человек уже знает — ему нужно,
о чём она. Два-три предложения своими словами: что она требует или
запрещает, к кому относится и при каких условиях применяется.
Дальше — ссылка и санкция, как обычно.

Дословно статью не переписывай: её полный текст человек откроет
отдельной клавишей, если понадобится."""


def system_prompt(mode: Mode, *, legal_context: str = "",
                  rag_enabled: bool = False, detailed: bool = False,
                  checklist: str = "", shape: str = "",
                  lawyer_role: str = "") -> str:
    """Собирает системный промпт режима, при наличии — с выдержками из базы.

    `shape` задаёт форму ответа там, где она зависит не от режима, а от
    самого вопроса: «listing» — перечень, «article» — разбор названной
    статьи. На экзамене форма своя и не переопределяется.
    """
    prompt = BY_MODE.get(mode, NORMAL)
    if mode is Mode.LAWYER and lawyer_role == "counsel":
        prompt += LAWYER_COUNSEL
    if mode is not Mode.EXAM:
        if shape == "listing":
            prompt += LISTING_FORMAT
        elif shape == "article":
            prompt += ARTICLE_FORMAT
    if mode is Mode.LAWYER and checklist:
        prompt += LAWYER_CHECKLIST.format(checklist=checklist)
    if detailed:
        prompt += DETAILED
    if not rag_enabled:
        return prompt + _NO_RAG_NOTICE
    if legal_context:
        return (prompt + _WITH_CONTEXT + legal_context
                + _allowlist(legal_context))
    return prompt + _EMPTY_CONTEXT
