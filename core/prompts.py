# По этим оборотам узнаём просьбу рассказать подробнее. Просьба звучит
# в продолжение предыдущего ответа, поэтому ловим её отдельно, а не
# гоняем через модель лишний раз.
DETAIL_TRIGGERS = (
    "подробнее", "подробней", "поподробнее", "точнее", "детальнее",
    "разверни", "разверн", "полностью", "целиком", "дословно",
    "полный текст", "что именно", "объясни", "расскажи подробно",
    "а можно подробнее", "уточни",
)


def wants_detail(question: str) -> bool:
    """Просит ли пользователь развёрнутый ответ вместо короткого."""
    lowered = question.lower()
    return any(trigger in lowered for trigger in DETAIL_TRIGGERS)

