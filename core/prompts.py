_ALLOWED_NUMBERS = re.compile(r"\[[^\]\n]+?,\s*п\.\s*([^\]\s]+)\]")


def _allowlist(legal_context: str) -> str:
    """Явный перечень номеров, которые разрешено называть.

    Общий запрет «не выдумывай» модель на 4 миллиарда параметров
    нарушает: в заключении она сочиняла «статью 14.1.2», хотя нужная
    норма лежала в контексте. Конкретный короткий список работает
    заметно лучше любого рассуждения о честности.
    """
    numbers = []
    for number in _ALLOWED_NUMBERS.findall(legal_context):
        if number not in numbers:
            numbers.append(number)
    if not numbers:
        return ""
    return ("\n\nРАЗРЕШЁННЫЕ НОМЕРА СТАТЕЙ (других не существует): "
            + ", ".join(numbers) +
            ".\nЛюбой номер вне этого списка — выдумка. Если нужной нормы "
            "в списке нет, напиши, что подходящей статьи в базе не нашлось.")


def verdict_prompt(legal_context: str = "") -> str:
    """Промпт для итогового заключения адвоката (ТЗ 5.4)."""
    if legal_context:
        return VERDICT + _WITH_CONTEXT + legal_context + _allowlist(legal_context)
