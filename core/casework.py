"""
Работа над делом в несколько проходов.

Один проход «надиктовка -> документ» упирается в потолок: модель
получает три десятка выдержек вперемешку и выбирает из них наугад.
Проверено на живом деле — за незачитанные права она поставила статью
о телесных повреждениях, а половина эпизодов до бумаги просто не
дошла.

Поэтому дело собирается так, как его собрал бы юрист:

1. РАЗБОР. Модель выписывает из надиктовки эпизоды — что именно
   произошло, по одному нарушению на строку. Ничего не оценивает,
   только вычленяет факты.
2. КВАЛИФИКАЦИЯ. Под каждый эпизод ищем норму в базе отдельным
   запросом. Это ключевой шаг: поиск по всей надиктовке приносит
   общее «про задержание», а поиск по эпизоду «обыскал без ордера» —
   статью об ордерах.
3. ЧЕРНОВИК. Документ пишется, имея готовую связку «эпизод — норма».
4. РЕВИЗИЯ. Модель сверяет черновик с эпизодами и нормами: не
   потерялся ли эпизод, та ли статья, нет ли лишнего.
5. ПРАВКА. Замечания вносятся в текст.

Время на это уходит минуты, и оно того стоит: документ идёт в дело,
а не в чат.
"""
from __future__ import annotations

import logging
import re
from dataclasses import dataclass, field

log = logging.getLogger(__name__)

# Строка эпизода в ответе модели: «- не зачитал права» или «1. ...».
_EPISODE_LINE = re.compile(r"^\s*(?:[-—•*]|\d+[.)])\s*(.+?)\s*$")

# Служебные строки, которые модель дописывает вокруг перечня.
_NOT_AN_EPISODE = re.compile(
    r"^(?:эпизод|нарушени|факт|вот|итак|список|перечень|ответ)\w*\s*:?\s*$",
    re.IGNORECASE)


@dataclass
class Episode:
    """Один эпизод дела: что произошло и какими нормами это закрыто."""

    text: str
    hits: list = field(default_factory=list)

    @property
    def covered(self) -> bool:
        return bool(self.hits)

    def as_line(self) -> str:
        """Строка для промпта: эпизод и найденные под него нормы."""
        if not self.hits:
            return f"  • {self.text}\n      норма не найдена"
        refs = "; ".join(f"{h.rule.citation()}" for h in self.hits[:2])
        return f"  • {self.text}\n      {refs}"


def parse_episodes(answer: str, limit: int = 12) -> list[str]:
    """Вытаскивает эпизоды из ответа модели.

    Модель любит обрамлять перечень вступлением и итогом; берём только
    строки списка. Пустой результат — не беда: дальше дело собирается
    по надиктовке целиком, как раньше.
    """
    found: list[str] = []
    for line in (answer or "").split(chr(10)):
        match = _EPISODE_LINE.match(line)
        if match:
            text = match.group(1).strip(" .;")
        else:
            # Модель часто отдаёт перечень без маркеров — просто
            # строками. Требовать дефис нельзя: на реальном деле
            # разбор из-за этого возвращал ноль эпизодов, и весь
            # конвейер откатывался к одному проходу.
            text = line.strip(" .;" + chr(9))
        # Отбрасываем заголовки вроде «Эпизоды:» и совсем короткие
        # обрывки: искать по ним нечего.
        if len(text) < 12 or _NOT_AN_EPISODE.match(text):
            continue
        if text not in found:
            found.append(text)
    return found[:limit]


def episodes_for_prompt(episodes: list[Episode]) -> str:
    """Связка «эпизод — норма» в том виде, в каком её читает модель."""
    return "\n".join(episode.as_line() for episode in episodes)


def uncovered(episodes: list[Episode]) -> list[str]:
    """Эпизоды, под которые норма не нашлась.

    Их не замалчиваем: в документе такое нарушение описывается
    словами, без ссылки, а человек видит, что норму искать придётся
    самому.
    """
    return [e.text for e in episodes if not e.covered]


# Замечания, по которым документ дополнят выдумкой. Вычитка охотно
# требует «указать дату подачи» и «время заседания» — данных, которых
# человек не называл и взять неоткуда.
# Замечания, которые предлагают дописать в дело новые обстоятельства.
# Вычитка знает только рассказ человека и нормы; придумать эпизод она
# не может — на проверке она предложила «добавить эпизод о том, что
# ответчик применил физическую силу», хотя об этом никто не говорил.
_INVENTS_FACTS = re.compile(
    r"добавить\s+эпизод|дополнить\s+(?:дело|документ)\s+эпизод|"
    r"указать,?\s+что\s+(?:истец|ответчик|сотрудник)\s+\w+л|"
    r"заменить\s+«?[А-ЯЁ][\w-]+»?\s+на\s+«?[А-ЯЁ]",
    re.IGNORECASE)

_DEMANDS_DATA = re.compile(
    r"указать\s+(?:дату|время|номер|фамилию|имя)|"
    r"добавить\s+(?:дату|время|номер\s+дела|подпись|фамилию)|"
    r"внести\s+(?:дату|время|номер)|"
    r"заполнить\s+(?:дату|время|поле)|"
    r"не\s+указан[аоы]?\s+(?:дата|время|номер|фамилия)",
    re.IGNORECASE)

# Ссылка на статью внутри замечания.
_NOTE_NUMBER = re.compile(r"\b(\d+(?:\.\d+)+)\b")


def filter_review_notes(notes: list[str], hits: list) -> list[str]:
    """Отсеивает замечания, которые сделают документ хуже.

    Вычитка полезна, когда указывает на пропущенный эпизод или чужую
    статью. Но она же требует дописать дату подачи и сослаться на
    норму, которой в базе нет, — по таким замечаниям модель дополняет
    документ выдумкой, и правка приносит вред.
    """
    allowed = {h.rule.number for h in hits}
    allowed |= {n.split(" ")[0] for n in allowed}

    kept: list[str] = []
    for note in notes:
        if _DEMANDS_DATA.search(note):
            log.info("Замечание отброшено (требует выдумать данные): %s",
                     note[:70])
            continue
        if _INVENTS_FACTS.search(note):
            log.info("Замечание отброшено (выдумывает факты): %s", note[:70])
            continue
        numbers = _NOTE_NUMBER.findall(note)
        if numbers and not any(n in allowed for n in numbers):
            log.info("Замечание отброшено (статья вне базы): %s", note[:70])
            continue
        kept.append(note)
    return kept


def revision_is_better(before: str, after: str, bad_before: list,
                       bad_after: list) -> tuple[bool, str]:
    """Стоит ли брать правленый документ вместо черновика.

    Проверено на живом деле: по замечаниям вычитки модель сменила вид
    документа с «о принятии» на «об отказе в принятии», переименовала
    город и приписала статьи кодекса, которого в этом мире нет. Правка
    обязана улучшать, иначе она не нужна.

    Возвращает (брать ли, причина отказа).
    """
    after = (after or "").strip()
    if not after:
        return False, "правка вернула пустой текст"
    if len(after) < len(before) * 0.6:
        return False, "правка обрезала документ"
    if len(bad_after) > len(bad_before):
        return False, ("после правки статей вне базы стало больше: "
                       + ", ".join(bad_after[:4]))

    # Заголовок бумаги менять нельзя: вид документа выбирает человек.
    head_before = _document_head(before)
    head_after = _document_head(after)
    if head_before and head_after and head_before != head_after:
        return False, f"правка подменила вид документа на «{head_after}»"
    return True, ""


# Вид бумаги: слово, с которого начинается её заголовок.
_FORM_WORDS = ("ОПРЕДЕЛЕНИЕ", "РЕШЕНИЕ", "ПРИГОВОР", "ПОСТАНОВЛЕНИЕ",
               "ИСКОВОЕ ЗАЯВЛЕНИЕ", "ХОДАТАЙСТВО", "ЖАЛОБА",
               "СУДЕБНЫЙ ОРДЕР", "ЗАКЛЮЧЕНИЕ")


def _document_head(text: str) -> str:
    """Вид бумаги из её заголовка: «ОПРЕДЕЛЕНИЕ о принятии...».

    Берём строку целиком, а не одно слово: «определение о принятии»
    и «определение об отказе в принятии» — разные бумаги, и подмена
    одной другой меняет смысл дела на противоположный.
    """
    for line in (text or "").split(chr(10)):
        line = " ".join(line.split())
        if not line or len(line) > 110:
            continue
        upper = line.upper()
        if any(upper.startswith(word) for word in _FORM_WORDS):
            return upper[:80]
    return ""
